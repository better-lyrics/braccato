//! Checks the WGSL shaders and translates them to GLSL ES 3.00 for WebGL2.
//!
//! A shader error therefore fails `cargo build` with naga's report, rather than surfacing as a
//! compile log in the browser. naga only runs here: it is a build-dependency, and what reaches the
//! wasm is the generated GLSL, included as strings, and a few names.
//!
//! For each `src/shaders/<name>.wgsl` this writes, into `OUT_DIR`:
//! - `<name>.vert.glsl` and `<name>.frag.glsl`, one per entry point (`vs_main`, `fs_main`);
//! - `<name>_names.rs`, the GLSL names naga gave the shader's resources. naga turns a WGSL uniform
//!   buffer into a uniform block per stage and pairs each texture with its sampler into one
//!   `sampler2D`, naming both after their binding. The renderer binds them by these constants, so it
//!   never spells out naga's naming scheme.

use naga::back::glsl;
use naga::valid::{Capabilities, ValidationFlags, Validator};
use naga::{AddressSpace, Module, ShaderStage};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

const SHADERS: &[&str] = &["quad"];
const ENTRY_POINTS: &[(ShaderStage, &str, &str)] =
    &[(ShaderStage::Vertex, "vs_main", "vert"), (ShaderStage::Fragment, "fs_main", "frag")];

fn main() {
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    println!("cargo:rerun-if-changed=build.rs");
    for name in SHADERS {
        let path = format!("src/shaders/{name}.wgsl");
        println!("cargo:rerun-if-changed={path}");
        if let Err(message) = translate(name, &path, Path::new(&out_dir)) {
            // A panic fails the build and prints the message, with naga's source excerpts intact.
            panic!("\n\nshader {path} failed to build:\n\n{message}\n");
        }
    }
}

fn translate(name: &str, path: &str, out_dir: &Path) -> Result<(), String> {
    let source = std::fs::read_to_string(path).map_err(|e| format!("cannot read it: {e}"))?;
    let module = naga::front::wgsl::parse_str(&source).map_err(|e| e.emit_to_string_with_path(&source, path))?;
    let info = Validator::new(ValidationFlags::all(), Capabilities::empty())
        .validate(&module)
        .map_err(|e| e.emit_to_string_with_path(&source, path))?;

    // GLSL name -> (WGSL name, binding), gathered across both stages.
    let mut blocks: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut samplers: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut bindings: BTreeMap<String, u32> = BTreeMap::new();

    for &(stage, entry_point, extension) in ENTRY_POINTS {
        let options = glsl::Options {
            version: glsl::Version::Embedded { version: 300, is_webgl: true },
            // No coordinate flip: the shader writes WebGL's clip space itself.
            writer_flags: glsl::WriterFlags::empty(),
            ..Default::default()
        };
        let pipeline =
            glsl::PipelineOptions { shader_stage: stage, entry_point: entry_point.to_string(), multiview: None };
        let mut glsl_source = String::new();
        let mut writer = glsl::Writer::new(
            &mut glsl_source,
            &module,
            &info,
            &options,
            &pipeline,
            naga::proc::BoundsCheckPolicies::default(),
        )
        .map_err(|e| format!("{entry_point}: cannot translate to GLSL: {e}"))?;
        let reflection = writer.write().map_err(|e| format!("{entry_point}: cannot translate to GLSL: {e}"))?;

        for (handle, glsl_name) in &reflection.uniforms {
            let variable = &module.global_variables[*handle];
            if variable.space != AddressSpace::Uniform {
                continue;
            }
            let wgsl_name = wgsl_name(&module, *handle)?;
            if let Some(binding) = &variable.binding {
                bindings.insert(wgsl_name.clone(), binding.binding);
            }
            push_unique(blocks.entry(wgsl_name).or_default(), glsl_name);
        }
        for (glsl_name, mapping) in &reflection.texture_mapping {
            let wgsl_name = wgsl_name(&module, mapping.texture)?;
            push_unique(samplers.entry(wgsl_name).or_default(), glsl_name);
        }

        let file = out_dir.join(format!("{name}.{extension}.glsl"));
        std::fs::write(&file, glsl_source).map_err(|e| format!("cannot write {}: {e}", file.display()))?;
    }

    let mut names = format!("// Generated by build.rs from src/shaders/{name}.wgsl. Do not edit.\n");
    for (wgsl_name, glsl_names) in &blocks {
        let constant = wgsl_name.to_uppercase();
        let binding = bindings.get(wgsl_name).copied().unwrap_or(0);
        writeln!(names, "\n/// The uniform blocks naga made of `{wgsl_name}`, one per stage that reads it.").unwrap();
        writeln!(names, "pub const {constant}_BLOCKS: &[&str] = &{glsl_names:?};").unwrap();
        writeln!(names, "/// The binding point `{wgsl_name}` is bound to, its WGSL `@binding`.").unwrap();
        writeln!(names, "pub const {constant}_BINDING: u32 = {binding};").unwrap();
    }
    for (wgsl_name, glsl_names) in &samplers {
        let constant = wgsl_name.to_uppercase();
        writeln!(names, "\n/// The `sampler2D` uniforms naga made of `{wgsl_name}` and its sampler, one per stage.")
            .unwrap();
        writeln!(names, "pub const {constant}_SAMPLERS: &[&str] = &{glsl_names:?};").unwrap();
    }
    let file = out_dir.join(format!("{name}_names.rs"));
    std::fs::write(&file, names).map_err(|e| format!("cannot write {}: {e}", file.display()))?;
    Ok(())
}

fn wgsl_name(module: &Module, handle: naga::Handle<naga::GlobalVariable>) -> Result<String, String> {
    module.global_variables[handle].name.clone().ok_or_else(|| "every resource needs a name".to_string())
}

fn push_unique(list: &mut Vec<String>, value: &str) {
    if !list.iter().any(|v| v == value) {
        list.push(value.to_string());
    }
}
